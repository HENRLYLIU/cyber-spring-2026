export const getRandomGreeting = (type: string, keyword?: string): string => {
  // 默认 fallback
  const userType = (
    Object.keys(GREETING_DATABASE).includes(type) ? type : "junior"
  ) as UserType;
  const templates = GREETING_DATABASE[userType].templates;

  // 随机选择一条
  let greeting = templates[Math.floor(Math.random() * templates.length)];

  // 简单的关键词注入（如果有点话，追加一句）
  if (keyword && keyword.trim().length > 0) {
    greeting += ` ps: 特别祝福包含关键词【${keyword}】的独家好运已注入内核！`;
  }

  return greeting;
};
